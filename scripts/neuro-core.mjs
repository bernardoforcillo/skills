#!/usr/bin/env node
// Builds the "Neuro-design core" block carried inside each design agent, from the lens files.
//
// The design agents carry the evidence they need in their own file, so a desk works without a
// reference lookup. A hand-copied block would drift from the lens files, so it is generated here
// and check-plugin.mjs fails when an agent's block differs from what this would write.
//
//   node scripts/neuro-core.mjs          show which agents are out of date
//   node scripts/neuro-core.mjs --write  rewrite the blocks
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const design = join(root, 'plugins', 'design');
const refs = join(design, 'skills', 'neuro-design', 'references');

const read = (p) => readFileSync(p, 'utf8').replaceAll('\r\n', '\n');

export const BEGIN = '<!-- neuro-core:begin — generated by scripts/neuro-core.mjs from the lens files; edit the lens file, not this block -->';
export const END = '<!-- neuro-core:end -->';

const SIX = [
  'attention-and-hierarchy',
  'cognitive-load-and-memory',
  'perception-gestalt-color',
  'motor-and-interaction',
  'emotion-and-memory',
  'typography-and-reading',
];

// Which lens checklists each desk carries (mirrors evidence-layer.md). `constants` adds the
// perceptual-limits table.
export const PLAN = {
  'design-lead': { constants: true, lenses: [] },
  'design-critic': { constants: true, lenses: SIX },
  'design-reviewer': { constants: true, lenses: SIX },
  'a11y-auditor': { constants: false, lenses: ['motor-and-interaction', 'cross-domain/neurodiversity-inclusive'] },
  'design-system-steward': { constants: false, lenses: ['perception-gestalt-color', 'typography-and-reading', 'motor-and-interaction'] },
  'content-designer': { constants: false, lenses: ['typography-and-reading', 'cognitive-load-and-memory', 'cross-domain/psycholinguistics-content'] },
  'design-metrics-analyst': { constants: false, lenses: ['cross-domain/behavioral-economics', 'cross-domain/social-influence-persuasion'] },
};

const section = (text, heading) => {
  const lines = text.split('\n');
  const start = lines.findIndex((l) => l.trim() === heading);
  if (start < 0) return null;
  const out = [];
  for (const l of lines.slice(start + 1)) {
    if (l.startsWith('## ')) break;
    out.push(l);
  }
  return out;
};

const checklist = (lens) => {
  const text = read(join(refs, `${lens}.md`));
  const title = text.split('\n')[0].replace(/^#\s*/, '').trim();
  const body = section(text, '## Design checklist');
  if (!body) throw new Error(`${lens}.md has no '## Design checklist'`);
  const items = body.filter((l) => l.startsWith('- '));
  return { title, items };
};

const constantsTable = () => {
  const text = read(join(refs, 'foundations', 'perceptual-limits.md'));
  const body = section(text, '## The constants, and what each one forbids');
  if (!body) throw new Error("perceptual-limits.md has no '## The constants, and what each one forbids'");
  return body.filter((l) => l.startsWith('|'));
};

export function render(agent) {
  const plan = PLAN[agent];
  if (!plan) return null;
  const out = [BEGIN, '## Neuro-design core (built in)', ''];
  out.push(
    'The evidence layer, carried in this file so the desk works without a lookup. Each item is a guideline from a cited lens file; the files hold the mechanism, the evidence and the bibliography keys. A lens `Blocking` becomes a review **blocker** only when a verified threshold is also crossed (see the evidence-layer reference); otherwise it is a **should**, stated as a question.',
    ''
  );
  if (plan.constants) {
    out.push('### The constants the lenses are guidance for', '', ...constantsTable(), '');
  }
  for (const lens of plan.lenses) {
    const { title, items } = checklist(lens);
    out.push(`### ${title} — checklist`, '', ...items, '');
  }
  out.push(END);
  return out.join('\n');
}

const agentFile = (agent) => join(design, 'agents', `${agent}.md`);
const ANCHOR = '\n## What you receive';

export function current(agent) {
  const text = read(agentFile(agent));
  const a = text.indexOf(BEGIN);
  const b = text.indexOf(END);
  if (a < 0 || b < 0) return null;
  return text.slice(a, b + END.length);
}

export function stale() {
  const out = [];
  for (const agent of Object.keys(PLAN)) {
    if (!existsSync(agentFile(agent))) { out.push([agent, 'agent file missing']); continue; }
    const have = current(agent);
    if (have === null) out.push([agent, 'has no neuro-core block']);
    else if (have !== render(agent)) out.push([agent, 'neuro-core block differs from the lens files']);
  }
  return out;
}

export function write() {
  for (const agent of Object.keys(PLAN)) {
    const file = agentFile(agent);
    let text = read(file);
    const block = render(agent);
    const a = text.indexOf(BEGIN);
    const b = text.indexOf(END);
    if (a >= 0 && b >= 0) {
      text = text.slice(0, a) + block + text.slice(b + END.length);
    } else {
      const at = text.indexOf(ANCHOR);
      if (at < 0) throw new Error(`${agent}.md has no '## What you receive' anchor`);
      text = text.slice(0, at) + '\n' + block + '\n' + text.slice(at);
    }
    writeFileSync(file, text);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--write')) {
    write();
    console.log(`neuro-core: wrote ${Object.keys(PLAN).length} agents`);
  } else {
    const s = stale();
    if (s.length) {
      for (const [a, why] of s) console.error(`  - ${a}: ${why}`);
      process.exit(1);
    }
    console.log('neuro-core: every design agent carries the current lens checklists');
  }
}
